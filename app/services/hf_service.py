import os
import json
import logging
import httpx
from typing import Dict, Any, List, Optional
from app.services.sentry_service import AgentSpan

logger = logging.getLogger("trailmates.hf")

# Default recommended Hugging Face open-weight model
DEFAULT_HF_MODEL = "google/gemma-2-9b-it"

SYSTEM_PROMPT = """You are TrailMates, a friendly outdoor companion AI.
Your goal is to help users spend less time on screens and step outside into nature.
Given the user's outdoor preferences, generate a practical, grounded, step-by-step outdoor adventure.

You MUST respond strictly in valid JSON format matching this schema:
{
  "title": "Creative Adventure Title",
  "description": "A warm, inspiring 1-2 sentence overview of the activity.",
  "total_duration_min": 30,
  "steps": [
    {
      "step_number": 1,
      "title": "Step Title",
      "description": "Specific action to do outdoors",
      "duration_min": 10
    }
  ],
  "items_to_bring": ["Item 1", "Item 2", "Item 3"],
  "safety_tips": ["Safety tip 1", "Leave no trace tip 2"],
  "phone_free_challenge": {
    "name": "Challenge Name",
    "instructions": "Screen-free sensory challenge",
    "phone_rule": "Put phone on Do Not Disturb!"
  },
  "reflection_question": "A thoughtful question to consider after finishing the walk."
}
Do not add any markdown formatting or extra text outside the JSON object.
"""

class HuggingFaceInferenceService:
    def __init__(self):
        self.hf_token = os.getenv("HF_TOKEN", "").strip()
        self.model_name = os.getenv("HF_MODEL", DEFAULT_HF_MODEL).strip()
        
        # Hugging Face Inference Providers Endpoints
        self.router_url = "https://router.huggingface.co/hf-inference/v1/chat/completions"
        self.serverless_v1_url = f"https://api-inference.huggingface.co/models/{self.model_name}/v1/chat/completions"
        self.legacy_url = f"https://api-inference.huggingface.co/models/{self.model_name}"

    def is_configured(self) -> bool:
        return bool(self.hf_token)

    async def generate_plan(
        self,
        activity: str,
        time_min: int,
        energy_level: str,
        setting: str,
        interests: List[str],
        optional_note: Optional[str] = None,
        tabpfn_metrics: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        with AgentSpan(
            name="Hugging Face Open-Weight Model Inference",
            op="ai.model.huggingface",
            description=f"Generates outdoor adventure plan via Hugging Face model ({self.model_name})"
        ) as span:
            span.set_data("hf_model", self.model_name)
            span.set_data("activity", activity)
            span.set_data("time_min", time_min)
            span.set_data("energy_level", energy_level)
            span.set_data("setting", setting)
            span.set_data("is_token_configured", self.is_configured())

            # Check if HF_TOKEN is configured
            if not self.is_configured():
                logger.info("HF_TOKEN not configured. Returning rule-based demo plan.")
                span.set_data("fallback_reason", "HF_TOKEN missing")
                return self._generate_rule_based_demo_plan(
                    activity, time_min, energy_level, setting, interests, optional_note, tabpfn_metrics
                )

            prompt = f"""
Create a personalized outdoor adventure plan with these user preferences:
- Primary Activity: {activity}
- Time Available: {time_min} minutes
- Energy Level: {energy_level}
- Outdoor Setting: {setting}
- Interests: {', '.join(interests) if interests else 'General Exploration'}
- User Note: {optional_note or 'None'}
- TabPFN Suitability Pace: {tabpfn_metrics.get('recommended_pace', 'Moderate pace') if tabpfn_metrics else 'Moderate'}

Ensure the plan fits exactly {time_min} minutes. Focus on mindfulness, sensory observation, and getting off screens.
Return JSON only.
"""

            headers = {
                "Authorization": f"Bearer {self.hf_token}",
                "Content-Type": "application/json"
            }

            chat_payload = {
                "model": self.model_name,
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": prompt}
                ],
                "temperature": 0.7,
                "max_tokens": 1000
            }

            async with httpx.AsyncClient(timeout=12.0) as client:
                # 1. Try Hugging Face Router API (OpenAI-compatible)
                try:
                    resp = await client.post(self.router_url, json=chat_payload, headers=headers)
                    if resp.status_code == 200:
                        res_data = resp.json()
                        raw_text = res_data["choices"][0]["message"]["content"]
                        plan_data = self._parse_json_response(raw_text)
                        plan_data["is_ai_generated"] = True
                        plan_data["attribution"] = f"Generated by Open-Weight AI ({self.model_name} via Hugging Face)"
                        plan_data["model_name"] = self.model_name
                        span.set_data("status", "success")
                        return plan_data
                except Exception as e:
                    logger.warning(f"HF Router endpoint attempt failed: {e}")

                # 2. Try Hugging Face Model Serverless v1 endpoint
                try:
                    resp = await client.post(self.serverless_v1_url, json=chat_payload, headers=headers)
                    if resp.status_code == 200:
                        res_data = resp.json()
                        raw_text = res_data["choices"][0]["message"]["content"]
                        plan_data = self._parse_json_response(raw_text)
                        plan_data["is_ai_generated"] = True
                        plan_data["attribution"] = f"Generated by Open-Weight AI ({self.model_name} via Hugging Face)"
                        plan_data["model_name"] = self.model_name
                        span.set_data("status", "success")
                        return plan_data
                except Exception as e:
                    logger.warning(f"HF Serverless v1 endpoint attempt failed: {e}")

                # 3. Try Legacy text generation endpoint
                try:
                    legacy_payload = {
                        "inputs": f"{SYSTEM_PROMPT}\n\nUser Prompt: {prompt}\n\nAssistant:",
                        "parameters": {"max_new_tokens": 1000, "temperature": 0.7, "return_full_text": False}
                    }
                    resp = await client.post(self.legacy_url, json=legacy_payload, headers=headers)
                    if resp.status_code == 200:
                        res_data = resp.json()
                        raw_text = res_data[0]["generated_text"] if isinstance(res_data, list) else str(res_data)
                        plan_data = self._parse_json_response(raw_text)
                        plan_data["is_ai_generated"] = True
                        plan_data["attribution"] = f"Generated by Open-Weight AI ({self.model_name} via Hugging Face)"
                        plan_data["model_name"] = self.model_name
                        span.set_data("status", "success")
                        return plan_data
                except Exception as e:
                    logger.warning(f"HF Legacy endpoint attempt failed: {e}")

            # Fallback to rule-based plan if all endpoints fail
            span.set_data("fallback_reason", "All HF API endpoints failed or timed out")
            demo_plan = self._generate_rule_based_demo_plan(
                activity, time_min, energy_level, setting, interests, optional_note, tabpfn_metrics
            )
            demo_plan["attribution"] = "Demo plan — AI inference error or timeout. Using rule-based fallback."
            return demo_plan

    def _parse_json_response(self, text: str) -> Dict[str, Any]:
        """Strips markdown code fences and parses JSON securely."""
        clean_text = text.replace("```json", "").replace("```", "").strip()
        start_idx = clean_text.find("{")
        end_idx = clean_text.rfind("}")
        if start_idx != -1 and end_idx != -1 and end_idx > start_idx:
            clean_text = clean_text[start_idx:end_idx+1]
        return json.loads(clean_text)

    def _generate_rule_based_demo_plan(
        self,
        activity: str,
        time_min: int,
        energy_level: str,
        setting: str,
        interests: List[str],
        optional_note: Optional[str],
        tabpfn_metrics: Optional[Dict[str, Any]]
    ) -> Dict[str, Any]:
        act_title = activity if activity != "Surprise me" else "Mindful Exploration"
        
        # Clean setting string grammatically
        if "Any" in setting or not setting:
            setting_clean = "Outdoors"
        elif "Park" in setting:
            setting_clean = "Park"
        elif "Garden" in setting:
            setting_clean = "Garden"
        elif "Neighborhood" in setting:
            setting_clean = "Neighborhood"
        elif "Trail" in setting or "Hiking" in setting:
            setting_clean = "Forest Trail"
        else:
            setting_clean = setting.split()[0]

        step_1_m = max(3, int(time_min * 0.2))
        step_2_m = max(8, int(time_min * 0.6))
        step_3_m = max(4, time_min - step_1_m - step_2_m)

        return {
            "title": f"The {act_title} Outdoor Escape" if setting_clean == "Outdoors" else f"The {act_title} in the {setting_clean}",
            "description": f"A refreshing {time_min}-minute screen-free adventure tailored to your {energy_level.lower()} energy level.",
            "total_duration_min": time_min,
            "steps": [
                {
                    "step_number": 1,
                    "title": "Unplug & Transition Outside",
                    "description": f"Step out into your nearby {setting.lower()}. Put your phone in Do Not Disturb mode and take 3 slow outdoor breaths.",
                    "duration_min": step_1_m
                },
                {
                    "step_number": 2,
                    "title": f"Engage in {act_title}",
                    "description": f"Walk at a {energy_level.lower()} pace. Notice 3 unique natural details (leaf patterns, light reflections, or bird movements) without taking out your phone.",
                    "duration_min": step_2_m
                },
                {
                    "step_number": 3,
                    "title": "Grounding Sit & Pause",
                    "description": "Find a bench, rock, or comfortable patch of grass. Sit quietly for a few minutes and feel the breeze against your face.",
                    "duration_min": step_3_m
                }
            ],
            "items_to_bring": [
                "Water bottle 💧",
                "Comfortable walking shoes 👟",
                "Weather jacket / sweater 🧥",
                "Phone in DO-NOT-DISTURB mode 📱🔒"
            ],
            "safety_tips": [
                "Stay aware of your physical surroundings and pedestrian traffic 🚶‍♂️",
                "Respect local flora & fauna — leave no trace behind 🌿",
                "Stay hydrated and dress appropriately for current weather 🌤️"
            ],
            "phone_free_challenge": {
                "name": "The 5-4-3-2-1 Sensory Challenge",
                "instructions": "Identify 5 natural textures, 4 ambient outdoor sounds, 3 leaf colors, 2 natural scents, and feel 1 cool breeze.",
                "phone_rule": "Keep your screen in your pocket until you finish your final step!"
            },
            "reflection_question": "What is one small natural detail you noticed today that you would have missed while staring at a screen?",
            "is_ai_generated": False,
            "attribution": "Demo plan — AI inference is not configured or currently unavailable",
            "model_name": self.model_name
        }
